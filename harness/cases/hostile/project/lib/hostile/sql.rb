# frozen_string_literal: true

module Hostile
  # Query text the reporting job sends. The heredocs are load-bearing: their bodies
  # are data, not code, and an engine that splices inside one emits a file that no
  # longer runs. The arithmetic around them is ordinary code and must still mutate.
  module Sql
    WINDOW_DAYS = 7
    DAY_SECONDS = 86_400

    def self.summary(table, limit)
      <<~SQL
        SELECT id, total
        FROM #{table}
        ORDER BY total DESC
        LIMIT #{limit}
      SQL
    end

    def self.banner(name)
      <<-TEXT
        report for #{name}
        generated by the hostile fixture
      TEXT
    end

    def self.owner_line(owner, rows)
      "owner: #{owner}\n" \
        "rows: #{rows}\n" \
        "window: #{WINDOW_DAYS} days"
    end

    def self.window_start(now)
      now - (WINDOW_DAYS * DAY_SECONDS)
    end

    def self.within?(timestamp, now)
      timestamp >= window_start(now)
    end
  end
end
