# frozen_string_literal: true

require "minitest/autorun"
require "hostile/sql"

class HostileSqlTest < Minitest::Test
  def test_summary_keeps_the_table_and_limit_inside_the_heredoc
    query = Hostile::Sql.summary("events", 10)
    assert_includes query, "FROM events"
    assert_includes query, "LIMIT 10"
    refute_includes query, "SQL"
  end

  def test_banner_interpolates_the_name_into_the_indented_heredoc
    lines = Hostile::Sql.banner("weekly").lines.map(&:strip)
    assert_equal ["report for weekly", "generated by the hostile fixture"], lines
  end

  def test_owner_line_is_an_interpolated_multi_line_string
    text = Hostile::Sql.owner_line("ada", 3)
    assert_equal ["owner: ada", "rows: 3", "window: 7 days"], text.lines.map(&:strip)
  end

  def test_window_start_subtracts_the_window
    assert_equal 1_000_000 - (7 * 86_400), Hostile::Sql.window_start(1_000_000)
  end

  def test_within_is_inclusive_at_the_boundary
    now = 1_000_000
    start = Hostile::Sql.window_start(now)
    assert Hostile::Sql.within?(start, now)
    assert Hostile::Sql.within?(now, now)
    refute Hostile::Sql.within?(start - 1, now)
  end
end
